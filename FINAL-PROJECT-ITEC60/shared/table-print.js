// Print any admin table as a sheet with the CineVault letterhead.
// Use: <button data-print-table="#table-id" data-print-title="Movies">Print</button>
// Prints every row that matches the table's current search (all pages, not
// just the one on screen), in the current sort order, without the action
// columns (View, Edit, Archive, Restore...). The letterhead and the admin's name
// come from includes/dashboard-header-sidebar.php.
(function () {
  const ACTION = /^(view|edit|delete|archive|restore|actions?|play)$/i;

  function rowsOf(table) {
    // DataTables keeps every row, even ones on other pages; ask it for them.
    if (window.DataTable && DataTable.isDataTable && DataTable.isDataTable(table)) {
      const api = new DataTable.Api(table);
      return api.rows({ search: 'applied', order: 'applied' }).nodes().toArray();
    }
    return [...table.tBodies[0].rows];
  }

  function cellText(cell) {
    const c = cell.cloneNode(true);
    c.querySelectorAll('button, .btn, i, svg, input, select, script').forEach(n => n.remove());
    return c.textContent.replace(/\s+/g, ' ').trim();
  }

  function esc(s) {
    return String(s).replace(/[&<>"']/g, ch => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[ch]));
  }

  function printTable(table, title) {
    const heads = [...table.tHead.rows[0].cells];
    const keep = heads.map((th, i) => (!ACTION.test(th.textContent.trim()) && !th.classList.contains('no-print')) ? i : -1).filter(i => i >= 0);
    const rows = rowsOf(table).filter(tr => tr.cells.length >= heads.length);
    const meta = document.getElementById('cv-print-meta');
    const letterhead = document.getElementById('cv-print-letterhead');
    const preparedBy = meta ? meta.dataset.admin : 'Admin';
    const site = meta ? meta.dataset.site : 'CineVault';
    const now = new Date();
    const date = now.toLocaleDateString(undefined, { year: 'numeric', month: 'long', day: 'numeric' });
    const time = now.toLocaleTimeString(undefined, { hour: 'numeric', minute: '2-digit' });
    const search = (table.closest('.dt-container') || document).querySelector('.dt-search input');
    const filter = search && search.value.trim() ? search.value.trim() : '';

    const head = keep.map(i => `<th>${esc(heads[i].textContent.trim())}</th>`).join('');
    const body = rows.length
      ? rows.map(tr => '<tr>' + keep.map(i => `<td>${esc(cellText(tr.cells[i]))}</td>`).join('') + '</tr>').join('')
      : `<tr><td colspan="${keep.length}" style="text-align:center;color:#8a7d68">Nothing to show.</td></tr>`;

    const html = `<!DOCTYPE html><html lang="en"><head><meta charset="UTF-8">
      <base href="${esc(location.href)}">
      <title>${esc(site)}: ${esc(title)}, ${esc(date)}</title>
      <link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Playfair+Display:wght@700;800&display=swap">
      <link rel="stylesheet" href="../shared/print-sheet.css">
      </head><body>
      <div class="no-print"><button type="button" onclick="window.print()">Print / Save as PDF</button></div>
      ${letterhead ? letterhead.innerHTML : ''}
      <p class="rpt-subject">${esc(title)}</p>
      <div class="rpt-meta-row">
        <div><span class="rpt-meta-label">Date</span><span class="rpt-meta-value">${esc(date)}</span></div>
        <div><span class="rpt-meta-label">Prepared by</span><span class="rpt-meta-value">${esc(preparedBy)}</span></div>
        <div><span class="rpt-meta-label">Rows</span><span class="rpt-meta-value">${rows.length}</span></div>
        ${filter ? `<div><span class="rpt-meta-label">Search</span><span class="rpt-meta-value">${esc(filter)}</span></div>` : ''}
      </div>
      <table class="rpt-table"><thead><tr>${head}</tr></thead><tbody>${body}</tbody></table>
      <p class="rpt-count">${rows.length} ${rows.length === 1 ? 'row' : 'rows'}${filter ? ' matching "' + esc(filter) + '"' : ''}.</p>
      <div class="rpt-generated">
        <p class="rpt-generated-line">Prepared by ${esc(preparedBy)}, ${esc(date)} at ${esc(time)}</p>
        <p class="rpt-generated-note">This list was generated by ${esc(site)}. It shows the records as of the time it was printed.</p>
      </div>
      <script>window.addEventListener('load', function () { setTimeout(function () { window.print(); }, 300); });<\/script>
      </body></html>`;

    const w = window.open('', '_blank');
    if (!w) { alert('Allow pop-ups for this site to print.'); return; }
    w.document.open();
    w.document.write(html);
    w.document.close();
  }

  document.addEventListener('click', e => {
    const btn = e.target.closest('[data-print-table]');
    if (!btn) return;
    const table = document.querySelector(btn.dataset.printTable);
    if (table) printTable(table, btn.dataset.printTitle || document.title);
  });
})();
