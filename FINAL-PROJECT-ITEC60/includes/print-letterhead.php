<?php
/*
 * The CineVault letterhead for printed sheets, from the admin Settings page
 * (site name, tagline and contact details). Blank contact fields are left off.
 * $base: path from the calling page to the FINAL-PROJECT-ITEC60 folder.
 */
function cv_print_letterhead($base = '../')
{
    $name = cv_setting('site_name', 'CineVault');
    $contact = array_filter([
        cv_setting('contact_address'),
        cv_setting('contact_phone') ? 'Phone: ' . cv_setting('contact_phone') : '',
        cv_setting('contact_email') ? 'Email: ' . cv_setting('contact_email') : '',
    ]);
    // "CineVault" prints as Cine + Vault in two colours, like the site's logo.
    $nameHtml = preg_match('/^(Cine)(Vault)$/i', $name, $m) ? e($m[1]) . '<span>' . e($m[2]) . '</span>' : e($name);
    ob_start(); ?>
<div class="rpt-letterhead">
  <img class="rpt-logo" src="<?php echo e($base); ?>MOVIE-IMG/HEADER-IMG/CINEVAULT-LOGO.svg?v=<?php echo CV_ASSET_VERSION; ?>" alt="">
  <div class="rpt-company">
    <div class="rpt-company-name"><?php echo $nameHtml; ?></div>
    <div class="rpt-company-tagline"><?php echo e(cv_setting('site_tagline', 'Classic movies and TV, free and in full.')); ?></div>
    <?php if ($contact): ?><div class="rpt-company-contact"><?php echo e(implode('  ·  ', $contact)); ?></div><?php endif; ?>
  </div>
</div>
<hr class="rpt-divider">
<?php
    return ob_get_clean();
}

/* Who printed it and when, at the bottom of every sheet. */
function cv_print_footer($adminName)
{
    ob_start(); ?>
<div class="rpt-generated">
  <p class="rpt-generated-line">Prepared by <?php echo e($adminName); ?>, <?php echo e(date('F j, Y \a\t g:i A')); ?></p>
  <p class="rpt-generated-note">This report was generated by <?php echo e(cv_setting('site_name', 'CineVault')); ?>. Figures are as of the time it was printed.</p>
</div>
<?php
    return ob_get_clean();
}
